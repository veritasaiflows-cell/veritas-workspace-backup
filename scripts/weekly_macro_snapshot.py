def macro_metric_by_key(macro_metrics: dict, key: str) -> dict[str, Any]:
    rows = macro_metrics.get("metrics") if isinstance(macro_metrics, dict) else []
    if not isinstance(rows, list):
        return {}
    for row in rows:
        if isinstance(row, dict) and row.get("key") == key:
            return row
    return {}


def macro_metric_line(row: dict[str, Any], fields: tuple[str, ...] = ("mom_pct", "yoy_pct")) -> str:
    if not row or row.get("status") != "ok":
        label = (row or {}).get("name") or "metric"
        return f"{label} unavailable"
    parts = [f"{row.get('latest_value', 'n/a')} as of {row.get('latest_date', 'n/a')}"]
    labels = {
        "mom_pct": "MoM",
        "qoq_annualized_pct": "QoQ annualized",
        "yoy_pct": "YoY",
        "delta": "delta",
    }
    for field in fields:
        value = row.get(field)
        if value is None:
            continue
        suffix = "%" if field.endswith("_pct") else ""
        parts.append(f"{labels.get(field, field)} {fmt(value, 3, suffix)}")
    return "; ".join(parts)


def macro_judgment_text(macro_judgment: dict, key: str, fallback: str) -> str:
    judgments = macro_judgment.get("judgments") if isinstance(macro_judgment, dict) else {}
    if not isinstance(judgments, dict):
        return fallback
    row = judgments.get(key)
    if not isinstance(row, dict):
        return fallback
    text = str(row.get("text") or "").strip()
    return text or fallback


