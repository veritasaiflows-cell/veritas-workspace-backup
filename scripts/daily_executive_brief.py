OUT_DIR          = WORKSPACE / "01. Dashboards" / "Daily Executive Summary"
OUT_JSON         = WORKSPACE / "tmp" / "daily-executive-brief.json"


def load_json(path: Path) -> dict | list | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"  WARNING: could not load {path.name}: {exc}")
        return None


def fmt(v: Any, decimals: int = 2, suffix: str = "") -> str:
    if v is None:
        return "N/A"
    try:
        return f"{float(v):,.{decimals}f}{suffix}"
    except Exception:
        return str(v)


def signed_pct(v: Any, decimals: int = 2) -> str:
    if v is None:
        return "N/A"
    try:
        n = float(v)
        sign = "+" if n >= 0 else ""
        return f"{sign}{n:,.{decimals}f}%"
    except Exception:
        return str(v)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


# ---------------------------------------------------------------------------
# Trust and confidence
# ---------------------------------------------------------------------------

def confidence_grade(validation: dict | None) -> tuple[str, str]:
    """Return (grade, rationale) — grade is one of high/moderate/reduced/critical."""
    if not validation:
        return ("reduced", "validation file missing")
    overall = (validation.get("overall") or "").lower()
    summ = validation.get("summary", {})
    crit = summ.get("critical", 0)
    warn = summ.get("warning", 0)
    if crit > 0:
        return ("critical", f"{crit} critical contradiction(s) on the dashboard")
    if warn == 0:
        return ("high", "no warnings on the dashboard")
    if warn <= 2:
        return ("moderate", f"{warn} warning(s) — usable with caveats")
    return ("reduced", f"{warn} warnings — degraded but usable")


