def build_key_events_next_week(earnings: dict, ms: dict, week_start: date, week_end: date, macro_judgment: dict) -> str:
    lines = ["## 7) Key Events Next Week\n"]
    next_monday = week_end + timedelta(days=3)  # Monday after this Friday
    next_friday = next_monday + timedelta(days=4)

    lines.append(f"*Window: {next_monday.isoformat()} → {next_friday.isoformat()}*\n")
    auctions = fetch_treasury_auctions(next_monday.isoformat(), next_friday.isoformat())
    lines.append("**Treasury auctions (official FiscalData):**")
    if auctions.get("status") == "ok" and auctions.get("auctions"):
        for row in auctions.get("auctions", [])[:12]:
            amount = row.get("offering_amt") or "amount n/a"
            lines.append(f"  - {row.get('auction_date')} — {row.get('security_term')} {row.get('security_type')} ({amount})")
    elif auctions.get("status") == "ok":
        lines.append("  - No Treasury auctions returned for the next-week window.")
    else:
        lines.append(f"  - Manual review required: {auctions.get('warning') or 'Treasury auction feed unavailable'}")

    next_week_earnings: list[str] = []
    for r in (earnings or {}).get("records", []):
        if r.get("error") or not r.get("next_earnings_date"):
            continue
        try:
            ed = datetime.strptime(r["next_earnings_date"], "%Y-%m-%d").date()
        except Exception:
            continue
        if next_monday <= ed <= next_friday:
            next_week_earnings.append(f"  - **{r['ticker']}** — {r['next_earnings_date']}")

    if next_week_earnings:
        lines.append("**Earnings (tracked universe):**")
        lines.extend(next_week_earnings)
    else:
        lines.append("- No tracked-universe earnings in next week's window.")

    fed = ((ms or {}).get("data", {}) or {}).get("fed", {}) or {}
    fomc = fed.get("next_fomc_date")
    if fomc:
        try:
            fd = datetime.strptime(fomc, "%Y-%m-%d").date()
            if next_monday <= fd <= next_friday:
                lines.append(f"\n**FOMC:** {fomc} — statement and press conference next week.")
        except Exception:
            pass

    lines.append(f"\n**Macro data (judgment draft):** {macro_judgment_text(macro_judgment, 'next_week_macro_data', 'Macro event judgment unavailable; manual review required.')}")
    return "\n".join(lines)


def build_regime_posture(scores: dict, deployment_surface: dict, macro_regime: dict) -> str:
    lines = ["## 8) Regime Posture and Portfolio Implication\n"]
    if scores and scores.get("records"):
        top = sorted(scores["records"], key=lambda r: -(r.get("total") or 0))[:5]
        lines.append("**Top 5 names by regime score:**")
        for r in top:
            lines.append(f"  - **{r['ticker']}** — {r.get('total','-')}/20  ({r.get('stance','')})")
    else:
        lines.append("- No regime scores available.")

    summary = (deployment_surface or {}).get("summary", {}) or {}
    groups = (deployment_surface or {}).get("groups", {}) or {}
    if summary:
        d = groups.get("DEPLOYABLE NOW") or []
        a = (groups.get("ALMOST DEPLOYABLE") or []) + (groups.get("ALMOST / NEAR-EARNINGS CAUTION") or [])
        b = (groups.get("BLOCKED") or []) + (groups.get("DO NOT TOUCH") or [])
        lines.append("")
        lines.append(f"**Deployment posture (machine):** {len(d)} deployable / {len(a)} almost / {len(b)} blocked.")
        for label, records in (("Deployable", d[:3]), ("Almost", a[:5]), ("Blocked/Do-not-touch", b[:5])):
            if records:
                tickers = ", ".join(r.get("ticker", "?") for r in records if isinstance(r, dict))
                lines.append(f"  - **{label}:** {tickers}")

    regime_label = ((macro_regime or {}).get("regime") or {}).get("label")
    if regime_label:
        lines.append(f"\n**Regime basis (machine):** {regime_label}.")

    lines.append("\n**Posture call (judgment):** _[Offensive / Defensive-neutral / Defensive — state basis]_.")
    lines.append("**One-line directive (judgment):** _[Fill]_.")
    return "\n".join(lines)


