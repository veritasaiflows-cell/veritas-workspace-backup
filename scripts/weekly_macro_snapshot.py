    lines.append(f"- **10Y Treasury:** {fmt(tr.get('10y'), 3)}% as of {tr.get('10y_as_of', 'n/a')} ({tr.get('10y_source','')}).")
    lines.append(f"- **3M T-bill:** {fmt(tr.get('3m_tbill'), 3)}% as of {tr.get('3m_as_of', 'n/a')} ({tr.get('3m_source','')}).")
