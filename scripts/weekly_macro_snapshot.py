def build_regime_assessment(ms: dict, scores: dict, macro_regime: dict) -> str:
    data = (ms or {}).get("data", {}) or {}
    fed = data.get("fed", {}) or {}
    vol = data.get("volatility", {}) or {}
    eq = data.get("equities", {}) or {}
    fx = data.get("fx", {}) or {}
    en = data.get("energy", {}) or {}
    credit = data.get("credit", {}) or {}
    breadth = data.get("breadth", {}) or {}
    sectors = data.get("sectors", {}) or {}
    pillars = (macro_regime or {}).get("pillars", {}) or {}

    lines = ["## 1) Macro Regime Assessment\n"]
    regime = scores.get("scoring_regime") if scores else None
    lines.append(f"- **Operating regime:** {regime or 'late-cycle, restrictive-policy, selective risk-on (default framing)'}.")
    lines.append(f"- **SPX:** {fmt(eq.get('spx'))}  |  **VIX:** {fmt(vol.get('vix'))}  |  **DXY:** {fmt(fx.get('dxy'))}.")
    lines.append(f"- **Brent:** ${fmt(en.get('brent'))}  |  **WTI:** ${fmt(en.get('wti'))}.")
    lines.append(f"- **Fed target:** {fmt(fed.get('target_low'), 2)}%–{fmt(fed.get('target_high'), 2)}% "
                 f"(confirmed {fed.get('target_confirmed','n/a')}).")
    credit_label = ((pillars.get("credit") or {}).get("label") or "").strip()
    if credit_label:
        lines.append(f"- **Credit:** {credit_label}.")
    elif credit:
        lines.append(f"- **Credit:** HY OAS {fmt(credit.get('high_yield_oas'))}%, IG OAS {fmt(credit.get('investment_grade_oas'))}% "
                     f"({credit.get('stress_regime', 'n/a')}).")
    breadth_label = ((pillars.get("breadth") or {}).get("label") or "").strip()
    if breadth_label:
        lines.append(f"- **Breadth:** {breadth_label}.")
    elif breadth:
        lines.append(f"- **Breadth:** {breadth.get('sectors_above_50dma', 'n/a')}/11 sectors above 50DMA; "
                     f"{breadth.get('breadth_regime', 'n/a')}.")
    ranked_sectors = [s for s in sectors.values() if isinstance(s, dict) and s.get("relative_vs_spx_pct") is not None]
    if ranked_sectors:
        strongest = max(ranked_sectors, key=lambda s: s.get("relative_vs_spx_pct") or 0)
        weakest = min(ranked_sectors, key=lambda s: s.get("relative_vs_spx_pct") or 0)
        lines.append(f"- **Sector leadership vs SPY:** strongest {strongest.get('ticker', 'n/a')} "
                     f"({fmt(strongest.get('relative_vs_spx_pct'), 1, '%')}); weakest {weakest.get('ticker', 'n/a')} "
                     f"({fmt(weakest.get('relative_vs_spx_pct'), 1, '%')}).")
    return "\n".join(lines)


