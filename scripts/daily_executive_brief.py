"""daily_executive_brief.py

Generate the autonomous Daily Executive Summary from cached tmp/ artifacts.

Reads:
    tmp/market-state.json
    tmp/trigger-sheet.json
    tmp/technical-refresh.json
    tmp/post-earnings-prep.json
    tmp/dashboard-validation.json
    tmp/deployment-check.json
    tmp/earnings-calendar.json
    tmp/dashboard-delta.json
    tmp/band-proposals.json (optional)

Writes:
    01. Dashboards/Daily Executive Summary/YYYY-MM-DD.md
        OR YYYY-MM-DD-machine.md if a session brief already exists
    tmp/daily-executive-brief.json

Behavior:
    - Critical rule: never overwrite a session-written brief. If the canonical
      file exists and was NOT auto-generated by this script, the script writes
      to YYYY-MM-DD-machine.md so the human/agent version takes precedence.
    - Quantitative sections auto-populate. Where judgment is required (regime
      framing, conviction calls), the script emits clear factual statements
      derived from data and explicitly labels anything that is data-driven vs.
      hand-curated.

Usage:
    python scripts/daily_executive_brief.py
"""

