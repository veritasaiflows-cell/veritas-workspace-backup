def build_energy_commodities(ms: dict, macro_judgment: dict) -> str:
    data = (ms or {}).get("data", {}) or {}
    en = data.get("energy", {}) or {}
    reference_date = (ms or {}).get("last_trading_day")
    brent_note = source_age_note(en.get("brent_as_of"), reference_date, "Brent")
    wti_note = source_age_note(en.get("wti_as_of"), reference_date, "WTI")
    lines = ["## 4) Energy and Commodities\n"]
    lines.append(f"- **Brent:** ${fmt(en.get('brent'))} as of {en.get('brent_as_of', 'n/a')} ({en.get('brent_source','')}).")
    lines.append(f"- **WTI:** ${fmt(en.get('wti'))} as of {en.get('wti_as_of', 'n/a')} ({en.get('wti_source','')}).")
    if brent_note or wti_note:
        lines.append(f"- **Oil freshness caveat:** {'; '.join(note for note in (brent_note, wti_note) if note)}")
    try:
        spread = float(en.get("brent")) - float(en.get("wti"))
        lines.append(f"- **Brent/WTI spread:** ${spread:,.2f}.")
    except Exception:
        pass
    lines.append(f"- **EIA inventory (judgment draft):** {macro_judgment_text(macro_judgment, 'eia_inventory', 'EIA inventory artifact unavailable; manual review required.')}")
    lines.append(f"- **Rig count (judgment draft):** {macro_judgment_text(macro_judgment, 'rig_count', 'Rig-count artifact unavailable; manual review required.')}")
    lines.append(f"- **Energy structure read:** {macro_judgment_text(macro_judgment, 'energy_structure', 'Energy structure judgment unavailable; manual review required.')}")
    return "\n".join(lines)


