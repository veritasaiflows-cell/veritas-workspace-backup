    lines.append(f"- **PCE:** headline {macro_metric_line(pce)}; core {macro_metric_line(core_pce)}.")
    lines.append(f"- **GDP:** real GDP {macro_metric_line(gdp, ('qoq_annualized_pct', 'yoy_pct'))}.")
    lines.append(
        f"- **Labor:** unemployment {macro_metric_line(unemployment, ('delta',))}; "
        f"nonfarm payrolls {macro_metric_line(payrolls, ('delta',))}; "
        f"average hourly earnings {macro_metric_line(wages)}."
    )
    lines.append(
        f"- **Claims:** initial {macro_metric_line(initial_claims, ('delta',))}; "
        f"continuing {macro_metric_line(continuing_claims, ('delta',))}."
    )
    lines.append(f"- **ISM manufacturing:** {macro_metric_line(ism, ('delta',))}.")
    lines.append(f"- **Pulse read (judgment draft):** {macro_judgment_text(macro_judgment, 'pulse_read', 'Macro judgment draft unavailable; interpret manually before final use.')}")
