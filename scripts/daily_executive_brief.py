def confidence_grade(validation: dict | None) -> tuple[str, str]:
    """Return (grade, rationale) — grade is one of high/moderate/reduced/critical."""
    if not validation:
        return ("reduced", "validation file missing")
    overall = (validation.get("overall") or "").lower()
    summ = validation.get("summary", {})
    crit = summ.get("critical", 0)
    warn = summ.get("warning", 0)
    if crit > 0:
        return ("critical", f"{crit} critical contradiction(s) on the dashboard")
    if warn == 0:
        return ("high", "no warnings on the dashboard")
    if warn <= 2:
        return ("moderate", f"{warn} warning(s) — usable with caveats")
    return ("reduced", f"{warn} warnings — degraded but usable")


